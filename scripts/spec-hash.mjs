// Extract the normative ANMA-1 sections (PRD Sections 10–13) into spec/anma-1.md and record its
// SHA-256 in packages/spec/src/spec-hash.ts.   node scripts/spec-hash.mjs [--check]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const check = process.argv.includes("--check");
const prd = readFileSync(new URL("../PRD.md", import.meta.url), "utf8");
const start = prd.indexOf("\n## 10. ANMA-1 file format");
const end = prd.indexOf("\n## 14. ");
if (start < 0 || end < 0) throw new Error("PRD section markers not found");
const body = `<!-- Generated by scripts/spec-hash.mjs from PRD.md Sections 10–13. Do not edit by hand. -->\n# ANMA-1 normative specification\n${prd.slice(start, end).trim()}\n`;
const sha = createHash("sha256").update(body).digest("hex");
const ts = `// Generated by scripts/spec-hash.mjs. SHA-256 of spec/anma-1.md (PRD Sections 10–13).\nexport const SPEC_SHA256 = "${sha}";\n`;
const specUrl = new URL("../spec/anma-1.md", import.meta.url);
const tsUrl = new URL("../packages/spec/src/spec-hash.ts", import.meta.url);
const stale = (url, text) => !existsSync(url) || readFileSync(url, "utf8") !== text;
if (check) {
  if (stale(specUrl, body) || stale(tsUrl, ts)) {
    console.error("spec/anma-1.md or packages/spec/src/spec-hash.ts is stale; run node scripts/spec-hash.mjs");
    process.exit(1);
  }
  console.log(`spec ok ${sha}`);
} else {
  writeFileSync(specUrl, body);
  writeFileSync(tsUrl, ts);
  console.log(`spec written ${sha}`);
}
